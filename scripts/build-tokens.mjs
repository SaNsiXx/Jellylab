// Generates app/tokens.css (Tailwind v4 @theme) from the brand pack's design tokens.
// Source of truth: assets/current_brand/07_DESIGN_TOKENS.json — edit that file, not the output.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "assets/current_brand/07_DESIGN_TOKENS.json");
const out = path.join(root, "app/tokens.css");

const t = JSON.parse(await readFile(src, "utf8"));
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

// Semantic aliases keep component code independent of raw palette names.
const colorAlias = {
  background: "bg",
  surface: "surface",
  surfaceElevated: "surface-2",
  border: "line",
  textPrimary: "fg",
  textSecondary: "muted",
};

const lines = [];
for (const [k, v] of Object.entries(t.colors)) {
  lines.push(`  --color-${colorAlias[k] ?? kebab(k)}: ${v};`);
}
for (const [k, v] of Object.entries(t.gradients)) lines.push(`  --gradient-${kebab(k)}: ${v};`);
for (const [k, v] of Object.entries(t.radii)) lines.push(`  --radius-${kebab(k)}: ${v};`);
for (const [k, v] of Object.entries(t.breakpoints)) lines.push(`  --breakpoint-${k}: ${v};`);
lines.push(`  --text-h1-desktop: ${t.typography.h1Desktop};`);
lines.push(`  --text-h1-mobile: ${t.typography.h1Mobile};`);
lines.push(`  --text-body-lg: ${t.typography.bodyLarge};`);
lines.push(`  --text-body: ${t.typography.body};`);
lines.push(`  --text-small: ${t.typography.small};`);
lines.push(`  --spacing-section: ${t.spacing.sectionDesktop};`);
lines.push(`  --spacing-section-mobile: ${t.spacing.sectionMobile};`);
for (const [k, v] of Object.entries(t.motion)) {
  if (k === "easing") lines.push(`  --ease-jelly: cubic-bezier(${v.join(", ")});`);
  else if (typeof v === "string") lines.push(`  --duration-${k}: ${v};`);
}

const css = `/* AUTO-GENERATED by scripts/build-tokens.mjs from 07_DESIGN_TOKENS.json — do not edit. */
@theme {
${lines.join("\n")}
}

:root {
  --container: ${t.spacing.container};
}
`;

await writeFile(out, css);
console.log(`tokens → ${path.relative(root, out)} (${lines.length} vars)`);
